#!/usr/bin/env node
/**
 * Generate open-source licenses file from production dependencies
 * 
 * Usage: node scripts/generate-licenses.js
 * 
 * Output: lib/generated/licenses.ts
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

console.log('🔍 Scanning production dependencies...\n');

// Get production dependencies only
const depsJson = execSync('npm ls --omit=dev --all --json', { encoding: 'utf-8', maxBuffer: 10 * 1024 * 1024 });
const depsTree = JSON.parse(depsJson);

// Collect unique packages
const packages = new Map();

function collectPackages(node, parentPath = []) {
  if (!node.dependencies) return;
  
  for (const [name, info] of Object.entries(node.dependencies)) {
    const key = `${name}@${info.version}`;
    
    if (!packages.has(key)) {
      // Try to read package.json for this package
      let pkgInfo = {
        name,
        version: info.version || '0.0.0',
        license: 'Unknown',
        licenseText: '',
        repository: '',
      };
      
      // Try to find package.json in node_modules
      const possiblePaths = [
        path.join(__dirname, '..', 'node_modules', name, 'package.json'),
        path.join(__dirname, '..', 'node_modules', ...parentPath, 'node_modules', name, 'package.json'),
      ];
      
      for (const pkgPath of possiblePaths) {
        if (fs.existsSync(pkgPath)) {
          try {
            const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
            pkgInfo.license = pkg.license || 'Unknown';
            pkgInfo.repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url || '';
            
            // Try to read LICENSE file
            const licensePaths = [
              path.join(path.dirname(pkgPath), 'LICENSE'),
              path.join(path.dirname(pkgPath), 'LICENSE.md'),
              path.join(path.dirname(pkgPath), 'LICENSE.txt'),
              path.join(path.dirname(pkgPath), 'LICENSE-MIT'),
              path.join(path.dirname(pkgPath), 'LICENCE'),
            ];
            
            for (const licensePath of licensePaths) {
              if (fs.existsSync(licensePath)) {
                pkgInfo.licenseText = fs.readFileSync(licensePath, 'utf-8');
                break;
              }
            }
            
            break;
          } catch (e) {
            console.warn(`Warning: Could not read ${pkgPath}`);
          }
        }
      }
      
      packages.set(key, pkgInfo);
    }
    
    // Recurse into dependencies
    collectPackages(info, [...parentPath, name]);
  }
}

collectPackages(depsTree);

console.log(`Found ${packages.size} unique production dependencies\n`);

// Group by unique license text
const licenseTexts = new Map();
const packagesByLicense = new Map();

for (const [key, pkg] of packages) {
  const licenseKey = pkg.licenseText || `NO_TEXT_${pkg.license}`;
  
  if (!licenseTexts.has(licenseKey)) {
    licenseTexts.set(licenseKey, pkg.licenseText);
    packagesByLicense.set(licenseKey, []);
  }
  
  packagesByLicense.get(licenseKey).push(pkg);
}

// Generate TypeScript file
const licenses = Array.from(packages.values())
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(pkg => {
    // Find the license text for this package
    const licenseKey = pkg.licenseText || `NO_TEXT_${pkg.license}`;
    const fullText = licenseTexts.get(licenseKey);
    
    return {
      id: `${pkg.name}@${pkg.version}`,
      name: pkg.name,
      version: pkg.version,
      license: pkg.license,
      licenseText: fullText || `License: ${pkg.license}\n\nFull license text not available. See package repository for details.`,
      repository: pkg.repository,
    };
  });

const tsContent = `/**
 * Generated open-source licenses
 * 
 * Do not edit manually. Generated by scripts/generate-licenses.js
 * Run: node scripts/generate-licenses.js
 */

export interface License {
  id: string;
  name: string;
  version: string;
  license: string;
  licenseText: string;
  repository: string;
}

export const licenses: License[] = ${JSON.stringify(licenses, null, 2)};
`;

// Ensure output directory exists
const outputDir = path.join(__dirname, '..', 'lib', 'generated');
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

const outputPath = path.join(outputDir, 'licenses.ts');
fs.writeFileSync(outputPath, tsContent);

console.log(`✅ Generated licenses file: ${path.relative(process.cwd(), outputPath)}`);
console.log(`   ${licenses.length} packages with ${licenseTexts.size} unique license texts\n`);
