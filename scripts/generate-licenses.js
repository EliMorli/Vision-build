#!/usr/bin/env node
/**
 * Generate open-source licenses screen from package.json dependencies
 * 
 * Usage: node scripts/generate-licenses.js
 * 
 * Outputs: lib/generated/licenses.ts
 */

/* global __dirname, process, console */
const fs = require('fs');
const path = require('path');

const OUTPUT_PATH = path.join(__dirname, '..', 'lib', 'generated', 'licenses.ts');
const PACKAGE_JSON_PATH = path.join(__dirname, '..', 'package.json');

// Read package.json
const packageJson = JSON.parse(fs.readFileSync(PACKAGE_JSON_PATH, 'utf-8'));

// Combine dependencies and devDependencies
const allDeps = {
  ...packageJson.dependencies,
  ...packageJson.devDependencies,
};

// Sort alphabetically
const sortedDeps = Object.keys(allDeps).sort();

// Generate license entries (name and version only, full text will be fetched at runtime)
const licenses = sortedDeps.map(name => ({
  name,
  version: allDeps[name],
}));

// Generate TypeScript file
const output = `/**
 * Auto-generated by scripts/generate-licenses.js
 * DO NOT EDIT MANUALLY
 */

export interface LicenseEntry {
  name: string;
  version: string;
}

export const licenses: LicenseEntry[] = ${JSON.stringify(licenses, null, 2)};
`;

// Ensure output directory exists
const outputDir = path.dirname(OUTPUT_PATH);
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

// Write output file
fs.writeFileSync(OUTPUT_PATH, output, 'utf-8');

console.log(`✅ Generated ${licenses.length} license entries to ${OUTPUT_PATH}`);
